#!/usr/bin/env node
/**
 * Generates the WhatsApp template manifest — LAN-168.
 *
 * ## Why this exists
 *
 * Production WhatsApp is template-only. Nothing dispatches unless the club has
 * created, in Meta's own template editor, a template whose name, language,
 * category, body and buttons match what the application actually sends. Until
 * this script existed, that list lived in a Linear ticket and the parameters
 * lived in `src/lib/delivery/templates.ts`, and the two had drifted apart on
 * every player-facing kind.
 *
 * So the manifest is *generated from the registry the adapter sends from*. If
 * the registry changes and this file is not regenerated, `--check` fails, the
 * same contract `types:check` holds for the generated database types.
 *
 * ## Why it transpiles rather than imports
 *
 * `templates.ts` is TypeScript and carries `import "server-only"`, which throws
 * outside a React Server Component. Rather than add a TypeScript runner as a
 * dependency for one script, it is transpiled in memory with the compiler the
 * repository already depends on and its one runtime import is stubbed. Every
 * other import in that module is type-only and erases.
 *
 * Usage:
 *   node scripts/generate-template-manifest.mjs            # write the manifest
 *   node scripts/generate-template-manifest.mjs --check    # fail if it is stale
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Module from "node:module";

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "src/lib/delivery/templates.ts");
const OUTPUT = resolve(ROOT, "docs/whatsapp-template-manifest.md");

/**
 * One message with every field populated, so each kind's own `parameters()`
 * produces the sample values Meta asks for at submission.
 *
 * Synthetic throughout, and deliberately so: no roster data, no real number and
 * no real token ever reaches a generated document. `HOST` stands in for the
 * permanent application hostname, which is LAN-126's to settle.
 */
const SAMPLE = {
  recipient: "447700900123",
  inviteeName: "Sam",
  eventName: "Thursday Practice",
  whenLabel: "Thursday 12 March, 7:00 pm",
  venue: "Marston Sports Ground",
  deadlineLabel: "Tuesday 10 March, 6:00 pm",
  attendingCount: 18,
  changeSummary: "The date and the venue have changed.",
  cancellationReason: "The club has cancelled this event.",
  outstandingCount: 12,
  rsvpUrl: "https://HOST/rsvp/EXAMPLETOKEN",
  yesUrl: "https://HOST/a/EXAMPLEYES",
  noUrl: "https://HOST/a/EXAMPLENO",
  queueUrl: "https://HOST/operate/admin/follow-ups?event=EXAMPLEEVENT",
  formUrl: "https://HOST/me/join/EXAMPLEFORM",
  stopUrl: "https://HOST/me/stop/EXAMPLESTOP",
};

function loadRegistry() {
  const ts = require("typescript");
  const source = readFileSync(SOURCE, "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  const compiled = new Module("templates", null);
  compiled._compile(outputText.replace('require("server-only")', "({})"), SOURCE);
  return compiled.exports;
}

function render(registry) {
  const { MESSAGE_KINDS, MESSAGE_TEMPLATES, TEMPLATE_NAMES, templateNameVariable } = registry;
  const lines = [
    "# WhatsApp template manifest",
    "",
    "<!-- Generated by scripts/generate-template-manifest.mjs. Do not edit by hand. -->",
    "",
    "Every template the club must create in its WhatsApp Business Account, generated",
    "from `src/lib/delivery/templates.ts` so that what is approved here is what the",
    "application sends. A mismatch between an approved template and the payload is",
    "Meta error `132000`, or worse, a delivered message with its sentences swapped.",
    "",
    "`HOST` is the permanent application hostname (LAN-126). Sample values are the",
    "registry's own output for a synthetic event; no roster data appears here.",
    "",
    "Regenerate with `npm run templates:manifest`. `npm run templates:check` fails",
    "when this file and the registry disagree.",
    "",
  ];

  for (const [index, kind] of MESSAGE_KINDS.entries()) {
    const template = MESSAGE_TEMPLATES[kind];
    const message = { ...SAMPLE, kind };
    const samples = template.parameters(message);
    lines.push(
      `## ${index + 1}. \`${TEMPLATE_NAMES[kind]}\``,
      "",
      `- **Kind** \`${kind}\``,
      `- **Category** ${template.whatsapp.category}`,
      "- **Language** `en_GB`",
      `- **Name override** \`${templateNameVariable(kind)}\``,
      "",
      "Body:",
      "",
      "```",
      ...template.whatsapp.body,
      "```",
      "",
    );

    if (template.parameterNames.length === 0) {
      lines.push("No body variables, so Meta asks for no sample values.", "");
    } else {
      lines.push("| Slot | Holds | Sample |", "| -- | -- | -- |");
      for (const [slot, name] of template.parameterNames.entries()) {
        lines.push(`| \`{{${slot + 1}}}\` | ${name} | ${samples[slot]} |`);
      }
      lines.push("");
    }

    if (template.whatsapp.buttons.length === 0) {
      lines.push("No buttons.", "");
    } else {
      lines.push("| Button | Type | Label | URL |", "| -- | -- | -- | -- |");
      for (const [position, button] of template.whatsapp.buttons.entries()) {
        const url = `https://HOST${button.path}${button.dynamic ? "{{1}}" : ""}`;
        const type = button.dynamic ? "URL, dynamic suffix" : "URL, static";
        lines.push(`| ${position} | ${type} | ${button.label} | \`${url}\` |`);
      }
      lines.push("");
    }
  }

  return lines.join("\n") + "\n";
}

const wanted = render(loadRegistry());

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    console.error(`Missing ${OUTPUT}. Run: npm run templates:manifest`);
    process.exit(1);
  }
  if (current !== wanted) {
    console.error(
      "The template manifest is stale: the delivery registry has changed since it was " +
        "generated. Run: npm run templates:manifest",
    );
    process.exit(1);
  }
  console.log("Template manifest is current.");
} else {
  writeFileSync(OUTPUT, wanted);
  console.log(`Wrote ${OUTPUT}`);
}
