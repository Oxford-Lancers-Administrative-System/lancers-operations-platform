#!/usr/bin/env node
/**
 * Creates the single pre-provisioned test user on the **local** Supabase stack.
 *
 *   npm run db:seed-user
 *
 * Public self-registration is disabled (supabase/config.toml), so accounts can
 * only be created through the Auth admin API. That is the point: this script is
 * the reference for how a real user gets provisioned later.
 *
 * Safety rails:
 *   * Refuses to run against anything other than a local Supabase URL.
 *   * Reads credentials from the environment, never from a committed file.
 *   * Prints no key material.
 *
 * Credentials come from .env.local, which is git-ignored. Populate it from
 * `npm run db:status` — local keys are generated by the CLI and are not secrets
 * in any meaningful sense, but they still never get committed.
 */
import { createClient } from "@supabase/supabase-js";
import { config } from "dotenv";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
config({ path: resolve(root, ".env.local"), quiet: true });

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const secretKey = process.env.SUPABASE_SECRET_KEY ?? process.env.SUPABASE_SERVICE_ROLE_KEY;
const email = process.env.TEST_USER_EMAIL ?? "test.user@oxfordlancers.local";
const password = process.env.TEST_USER_PASSWORD;

if (!url || !secretKey) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SECRET_KEY. Copy .env.example to .env.local\nand fill it from `npm run db:status`.",
  );
  process.exit(1);
}

const isLocal = /^https?:\/\/(127\.0\.0\.1|localhost|host\.docker\.internal|kong)(:\d+)?/.test(url);
if (!isLocal) {
  console.error(`Refusing to run: ${url} is not a local Supabase URL.`);
  console.error("This script provisions users with a privileged key and is local-only by design.");
  process.exit(1);
}

if (!password) {
  console.error("Set TEST_USER_PASSWORD in .env.local (minimum 12 characters).");
  process.exit(1);
}

const supabase = createClient(url, secretKey, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const { data: existing, error: listError } = await supabase.auth.admin.listUsers({ perPage: 1000 });
if (listError) {
  console.error(`Could not list users: ${listError.message}`);
  process.exit(1);
}

const match = existing.users.find((user) => user.email?.toLowerCase() === email.toLowerCase());

if (match) {
  const { error } = await supabase.auth.admin.updateUserById(match.id, {
    password,
    email_confirm: true,
  });
  if (error) {
    console.error(`Could not update ${email}: ${error.message}`);
    process.exit(1);
  }
  console.log(`Updated existing local test user: ${email}`);
} else {
  const { error } = await supabase.auth.admin.createUser({
    email,
    password,
    email_confirm: true,
  });
  if (error) {
    console.error(`Could not create ${email}: ${error.message}`);
    process.exit(1);
  }
  console.log(`Created local test user: ${email}`);
}

console.log(`Sign in at http://localhost:${process.env.PORT ?? "3000"}/login`);
